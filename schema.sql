CREATE DATABASE IF NOT EXISTS eventdb;
USE eventdb;
-- (the app also creates these automatically)
CREATE TABLE IF NOT EXISTS venues (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, capacity INT NOT NULL);
CREATE TABLE IF NOT EXISTS events (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(150) NOT NULL, type VARCHAR(20) NOT NULL,
  event_date VARCHAR(10) NOT NULL, start_time VARCHAR(5) NOT NULL, end_time VARCHAR(5) NOT NULL, capacity INT NOT NULL, venue_id INT NULL);
CREATE TABLE IF NOT EXISTS participants (id INT AUTO_INCREMENT PRIMARY KEY, event_id INT NOT NULL, name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL, phone VARCHAR(15) NOT NULL);
